"""The ``issues`` family of the GitHub operations index: issues, their comments, events, labels, milestones, assignees,
artifacts, dependencies, related issues, field values, suggestions, sub-issues and timeline (design D5).

Each record is the section of ``docs/api-reference/github/rest/issues.md`` its operation ID names: its method and path
(the index row), the names of its ``query`` rows, and the first-level fields of its request body
(``labels[]{variant 2}.name`` is a field of ``labels``, ``{variant 1}.labels`` the ``labels`` of the object variant).
No path parameter of the family may contain ``/``, so no record has a multi-segment parameter. Every section with a
``Paging:`` line returns a bare array, so its record pages by ``link`` with no item key (``conventions.md`` "Lists
wrapped in an object" names none of them) -- but ``issues/get-issue-artifact``: its ``200`` is one artifact whose
``versions`` are the paged list, so it is declared ``Paging.NONE`` and sends one request, ``page`` and ``per_page``
among its query names (#32 DL-004). Every other record sends one request.

Every record but ``issues/create`` is sent by ``call <operation-id>`` (#28), which refuses that one and names the
subcommand that sends it. The compatibility commands that send records of the family, by D5's table:

- ``list-issues``: ``issues/list-for-repo``, followed by ``link``;
- ``get-issue``, ``get-issue-comments``: ``issues/get``; ``issues/list-comments``, every page by ``link``;
- ``comment-issue``, ``create-issue``, ``update-issue``: ``issues/create-comment``, ``issues/create``,
  ``issues/update``;
- ``reopen-issue``, ``checklist``: ``issues/get``, ``issues/update``;
- the claim commands, with ``users/get-authenticated``: ``start-issue`` (``issues/get``, ``issues/add-labels``,
  ``issues/add-assignees``), ``release-issue`` (``issues/get``, ``issues/update``, ``issues/remove-assignees``),
  ``claim-check`` (``issues/get``), and ``label-add``, ``label-remove``, ``assign`` (``issues/add-labels``,
  ``issues/remove-label``, ``issues/get``, ``issues/add-assignees``, ``issues/remove-assignees``).

No operation of the family is pending.
"""

