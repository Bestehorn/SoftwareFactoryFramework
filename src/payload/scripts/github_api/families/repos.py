"""The ``repos`` family of the GitHub operations index: one record per ``repos/`` operation ID of the reference but
``repos/upload-release-asset``.

Each record is its section of ``docs/api-reference/github/rest/<category>.md`` (``branches``, ``collaborators``,
``commits``, ``deploy-keys``, ``deployments``, ``metrics``, ``orgs``, ``pages``, ``releases``, ``repos``), in the order
of the files and of their sections: the operation line's method and path, the ``query`` rows of its ``Parameter``
table, and the first-level names of its JSON request body. ``multi_segment`` holds each path parameter whose row reads
"may contain `/` (multi-segment path)" (``conventions.md`` "Path parameters"), so ``registry.expand`` keeps its ``/``.
Every record sends ``API_VERSION_DEFAULT`` and ``ACCEPT_JSON``.

A section with a ``Paging:`` line or a ``Link`` response header is ``Paging.LINK``: its ``item_key`` is the one key
after "items in" (``conventions.md`` "Lists wrapped in an object"), ``None`` where the body is the array.
``registry.pages`` follows a ``rel="next"`` target when the response sends one and stops after the first page when it
does not. ``repos/get-commit`` and ``repos/compare-commits`` name two keys (``parents`` or ``files``, ``commits`` or
``files``), so they are ``Paging.NONE`` and ``call`` prints the one page asked for; so is every other record.

``repos/get-combined-status-for-ref`` is the record ``get-pr-checks`` sends. The records whose call commits to,
creates, moves or renames a branch (``repos/merge``, ``repos/merge-upstream``, ``repos/rename-branch``,
``repos/create-or-update-file-contents``, ``repos/delete-file``) are declared, and ``call`` refuses them by
``commands/call.py`` ``GATED_OPERATIONS``. ``repos/upload-release-asset`` stays on ``PENDING``: its body is the
asset's bytes, sent to the upload origin, which ``call`` does not send (issue #27, DL-002).
"""

