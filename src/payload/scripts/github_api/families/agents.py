"""The ``agents`` family of the GitHub operations index: the ``agents`` secrets and variables of an organization and
of a repository, and the repositories an organization secret or variable is selected for.

Each record is the section of ``docs/api-reference/github/rest/agents.md`` its operation ID names: its method and path,
the names of its ``query`` rows, and the first-level fields of its request body. No path parameter spans segments, and
every record sends ``API_VERSION_DEFAULT`` and ``ACCEPT_JSON``.

The eight sections with a ``Paging:`` line page by ``link``, their items in ``secrets``, ``variables`` or
``repositories`` (``conventions.md`` "Lists wrapped in an object"). The two lists of an organization secret's or
variable's selected repositories document no ``Link`` header: ``registry.pages`` follows a ``rel="next"`` target when
the response sends one and stops after the first page when it does not. Every other record sends one request.

A secret write sends ``encrypted_value`` and ``key_id`` as the caller gives them (issue #31 DL-002). Every record is
sent by ``call <operation-id>`` (#28); none writes a branch or creates issues, and no operation of the family is
pending.
"""

