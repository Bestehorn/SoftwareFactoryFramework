"""The ``orgs`` family of the GitHub operations index: one record per ``orgs/`` operation ID of the reference.

Each record is its section of ``docs/api-reference/github/rest/orgs.md``, in the order of its sections: the operation
line's method and path, the ``query`` rows of its ``Parameter`` table, and the first-level names of its JSON request
body (``deployments[].name`` is a field of ``deployments``; ``{variant 1}.subject_digests`` names ``subject_digests``).
``multi_segment`` holds each path parameter whose row reads "may contain `/` (multi-segment path)" (``conventions.md``
"Path parameters"), so ``registry.expand`` keeps its ``/``: ``subject_digest`` of
``orgs/list-artifact-storage-records``, ``orgs/delete-attestations-by-subject-digest`` and ``orgs/list-attestations``.
A body field that reads so (``version``, ``deployments[].version``) is no path parameter. Every record sends
``API_VERSION_DEFAULT`` and ``ACCEPT_JSON``.

A section with a ``Paging:`` line or a ``Link`` response header is ``Paging.LINK``: its ``item_key`` is the one key
after "items in" (``conventions.md`` "Lists wrapped in an object"), ``None`` where the body is the array. The ``POST``
``orgs/list-attestations-bulk`` pages by cursor with no ``Link`` header, and ``registry.pages`` asks for each page with
a ``GET`` and no body (#28 design D3), so it is ``Paging.NONE``: ``call`` sends its one request, body included, and
prints the page. So is every other record.

No record commits to, creates, moves or renames a branch, creates an issue or merges, so ``call`` gates none of them.
The records whose path names ``{org}`` are unreachable from an ``sff-test-*`` repository (#28 design D5). No operation
of the family is pending.
"""

