"""The ``plan`` endpoint family of the GitLab wrapper: issues, notes, labels, boards, epics, milestones and wikis.

Each record is transcribed from the attribute table of its section of ``docs/api-reference/gitlab/rest/plan.md``
(issue #13, design.md D1 and D5): the method, the path as ``operations-index.md`` writes it, and one ``Param`` per query
or body attribute with the table's Type column as its ``Kind``. Part 1 declares the records the ``issue`` and ``label``
commands compose (design.md D6): ``issue list``, ``show``, ``create``, ``comment``, ``start``, ``claim-check``,
``release``, ``label-add``, ``label-remove``, ``assign``, ``close`` and ``reopen``; ``label list`` and
``label create``. ``PENDING`` holds the ``(method, path)`` key of every other index row of this family; no other family
links any of them.

Standard library only; Python 3.9.
"""

