"""The ``verify`` endpoint family of the GitLab wrapper: CI/CD — pipelines, jobs, runners, variables, environments,
deployments, releases and clusters.

Each record is transcribed from the attribute table of its section of ``docs/api-reference/gitlab/rest/verify.md``
(issue #13, design.md D1 and D5): the method, the path as ``operations-index.md`` writes it, and one ``Param`` per query
or body attribute with the table's Type column as its ``Kind``. Part 1 declares the records the ``pipeline`` commands
compose (design.md D6): ``pipeline status``, ``pipeline log`` and ``pipeline wait``. ``PENDING`` holds the
``(method, path)`` key of every other index row of this family; no other family links any of them.

Standard library only; Python 3.9.
"""

