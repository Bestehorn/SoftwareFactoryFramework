"""Build the GitHub and GitLab API reference under docs/api-reference/ from the official machine-readable sources.

Run from the repository root, with the sources downloaded as described in docs/api-reference/README.md:

    python -I scripts/api_reference/build.py --sources tmp/api-sources --out docs/api-reference

Every file this writes starts with a "Generated by" banner; afterwards, files carrying that banner that this
run did not write are deleted, so a category that disappears upstream disappears here. Hand-written files (the
conventions pages) have no banner and are never touched.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # -I drops the script directory from sys.path

import github_graphql  # noqa: E402
import github_rest  # noqa: E402
import gitlab_graphql  # noqa: E402
import gitlab_rest  # noqa: E402
from common import GENERATOR, WRITTEN, banner, table, write  # noqa: E402
from graphql_model import KIND_FILES, KIND_TITLES, Renderer  # noqa: E402

GITHUB_OPENAPI = "github-openapi/api.github.com.json"
GITHUB_GRAPHQL = "github-graphql/schema.docs.graphql"
GITLAB_DOCS = "gitlab-docs/doc/api"
GITLAB_OPENAPI = "gitlab-openapi/openapi_v2.yaml"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def remove_stale(out: Path) -> list[str]:
    """Delete generated files (they carry the banner) that this run did not write; hand-written files stay."""
    removed = []
    for path in out.rglob("*.md"):
        if path.resolve() in WRITTEN:
            continue
        with path.open(encoding="utf-8") as handle:
            generated = handle.readline().startswith(f"<!-- Generated by {GENERATOR}")
        if generated:
            path.unlink()
            removed.append(path.relative_to(out).as_posix())
    return removed


def graphql_index(out: Path, title: str, source: str, result: dict, renderer: Renderer, official: str) -> None:
    counts = result["counts"]
    rows = []
    for stem, label in (("queries", "Queries (root `Query` fields)"), ("mutations", "Mutations")):
        for name, n, span in renderer.root_pages.get(stem, []):
            rows.append([f"[{label}{' — ' + span if span else ''}]({name})", str(n)])
    for page, types in result["files"].items():
        kind = types[0].kind if types else "scalar"
        span = f" — {types[0].name} … {types[-1].name}" if types and page[:-3] != KIND_FILES[kind] else ""
        rows.append([f"[{KIND_TITLES[kind]}{span}]({page})", str(len(types))])
    rows.append(["[Directives](directives.md)", str(counts["directives"])])
    lines = [
        banner(source),
        "",
        f"# {title}",
        "",
        f"Generated from {source}. Official reference: {official}",
        "",
        "- Endpoint, authentication, pagination, limits, errors, uploads: [conventions](conventions.md)",
        "- How to read the tables: [notation](../../README.md#reading-the-generated-tables)",
        f"- Input and payload types used by exactly one mutation ({counts['documented with their mutation']}) "
        "are documented with that mutation and not repeated in the type files.",
        "",
        *table(["Reference", "Entries"], rows),
    ]
    write(out / "README.md", lines)


def sources_table(src: Path, rows: list[tuple[str, str, str, str]]) -> list[str]:
    """The provenance of a reference: what was read, from where, at which pin, with which content hash."""
    body = [
        [label, f"`{rel}`", url, pin, f"`{sha256(src / rel)}`" if (src / rel).is_file() else "(folder)"]
        for label, rel, url, pin in rows
    ]
    return [
        "## Sources",
        "",
        *table(["Source", "Local copy (under the sources folder)", "Fetched from", "Pin", "SHA-256"], body),
        "",
    ]


def build_github(src: Path, out: Path, pins: dict) -> dict:
    rest = github_rest.build(src / GITHUB_OPENAPI, out, pins["github_rest"])
    lines = [
        banner(f"api.github.com.json ({pins['github_rest']})"),
        "",
        "# GitHub API reference",
        "",
        f"REST: {rest['operations']} operations on {rest['paths']} paths in {len(rest['categories'])} categories, "
        f"generated from GitHub's OpenAPI description (OpenAPI {rest['openapi']}, description version "
        f"{rest['version']}, {pins['github_rest']}). GraphQL: see [graphql/README.md](graphql/README.md).",
        "",
        "- Mechanics (hosts, auth, headers and API versions, encoding, pagination, uploads, downloads, rate "
        "limits, errors): [conventions](conventions.md)",
        "- Every operation sorted by path: [operations-index.md](operations-index.md)",
        "- How to read the tables: [notation](../README.md#reading-the-generated-tables)",
        "",
        *sources_table(
            src,
            [
                ("REST: OpenAPI description", GITHUB_OPENAPI, pins["github_rest_url"], pins["github_rest"]),
                ("GraphQL: public schema (SDL)", GITHUB_GRAPHQL, pins["github_graphql_url"], pins["github_graphql"]),
            ],
        ),
        "## REST categories",
        "",
        *table(["Category", "Operations", "Subcategories"], rest["categories"]),
    ]
    write(out / "README.md", lines)
    schema = github_graphql.load(src / GITHUB_GRAPHQL)
    renderer = Renderer(
        schema, out / "graphql", "GitHub GraphQL API", f"schema.docs.graphql ({pins['github_graphql']})"
    )
    gql = renderer.render()
    graphql_index(
        out / "graphql",
        "GitHub GraphQL API reference",
        f"schema.docs.graphql ({pins['github_graphql']})",
        gql,
        renderer,
        "https://docs.github.com/graphql/reference",
    )
    return {"rest": rest, "graphql": gql["counts"]}


def build_gitlab(src: Path, out: Path, pins: dict) -> dict:
    rest = gitlab_rest.build(src / GITLAB_DOCS, src / GITLAB_OPENAPI, out, pins["gitlab"])
    lines = [
        banner(f"gitlab-org/gitlab doc/api ({pins['gitlab']})"),
        "",
        "# GitLab API reference",
        "",
        f"REST (v4): {rest['entries']} documented sections with {rest['docs_endpoints']} endpoints on "
        f"{rest['pages']} docs pages, plus {rest['openapi_only']} operations that only GitLab's OpenAPI file "
        f"lists ({rest['openapi_matched']} of its {rest['openapi_ops']} operations match a docs page). "
        f"Generated from gitlab-org/gitlab `doc/api` ({pins['gitlab']}). GraphQL: see "
        "[graphql/README.md](graphql/README.md).",
        "",
        "- Mechanics (hosts, auth and token types, encoding, pagination, uploads, downloads, rate limits, "
        "errors): [conventions](conventions.md)",
        "- Every endpoint sorted by path: [operations-index.md](operations-index.md)",
        "- How to read the tables: [notation](../README.md#reading-the-generated-tables)",
        "",
        *sources_table(
            src,
            [
                ("REST and GraphQL: docs pages `doc/api`", GITLAB_DOCS, pins["gitlab_docs_url"], pins["gitlab"]),
                ("REST: OpenAPI v2 file (partial)", GITLAB_OPENAPI, pins["gitlab_openapi_url"], pins["gitlab"]),
            ],
        ),
        "## REST, grouped by the DevOps stage that owns each docs page",
        "",
        *table(["Stage", "Pages", "Sections", "Endpoints", "Docs pages"], rest["stages"]),
    ]
    if rest["openapi_only"]:
        lines += [
            "",
            f"Operations only in `openapi_v2.yaml`: [rest/openapi-only.md](rest/openapi-only.md) "
            f"({rest['openapi_only']}).",
        ]
    write(out / "README.md", lines)
    schema = gitlab_graphql.load(src / GITLAB_DOCS / "graphql" / "reference")
    source = f"doc/api/graphql/reference ({pins['gitlab']})"
    renderer = Renderer(schema, out / "graphql", "GitLab GraphQL API", source)
    gql = renderer.render()
    graphql_index(
        out / "graphql",
        "GitLab GraphQL API reference",
        source,
        gql,
        renderer,
        "https://docs.gitlab.com/api/graphql/reference/",
    )
    return {"rest": {k: v for k, v in rest.items() if k not in ("stages", "sizes")}, "graphql": gql["counts"]}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sources", type=Path, required=True, help="folder holding the downloaded sources")
    parser.add_argument("--out", type=Path, required=True, help="docs/api-reference")
    parser.add_argument("--pins", type=Path, help="JSON file with the source pins (default: <sources>/pins.json)")
    args = parser.parse_args()
    pins = json.loads((args.pins or args.sources / "pins.json").read_text(encoding="utf-8"))
    args.out.mkdir(parents=True, exist_ok=True)
    stats = {
        "github": build_github(args.sources, args.out / "github", pins),
        "gitlab": build_gitlab(args.sources, args.out / "gitlab", pins),
        "sha256": {name: sha256(args.sources / name) for name in (GITHUB_OPENAPI, GITHUB_GRAPHQL, GITLAB_OPENAPI)},
    }
    stats["removed stale files"] = remove_stale(args.out)
    print(json.dumps(stats, indent=1, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
