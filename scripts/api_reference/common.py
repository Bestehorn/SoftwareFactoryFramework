"""Shared Markdown helpers for the API reference generators (GitHub-flavored Markdown output)."""

from __future__ import annotations

import json
import re
from pathlib import Path

GENERATOR = "scripts/api_reference/build.py"


class Slugger:
    """GitHub's heading-anchor rule: lowercase, drop punctuation, spaces to hyphens, repeats get -1, -2, ..."""

    def __init__(self) -> None:
        self.seen: dict[str, int] = {}

    def slug(self, heading: str) -> str:
        text = re.sub(r"`|\*\*|\[|\]\([^)]*\)", "", heading).strip().lower()
        base = re.sub(r"[^\w\- ]", "", text).replace(" ", "-")
        if base not in self.seen:
            self.seen[base] = 0
            return base
        self.seen[base] += 1
        return f"{base}-{self.seen[base]}"


def cell(value: object) -> str:
    """Render a value for a Markdown table cell: no newlines, escaped pipes."""
    text = "" if value is None else str(value)
    return re.sub(r"\s*\n\s*", " ", text).replace("|", "\\|").strip()


def code(value: object) -> str:
    text = str(value)
    if text == "":
        return '`""`'
    tick = "``" if "`" in text else "`"
    pad = " " if tick == "``" else ""
    return f"{tick}{pad}{text}{pad}{tick}"


def jsonish(value: object) -> str:
    return code(json.dumps(value, ensure_ascii=False, separators=(",", ":")))


def literal(value: object) -> str:
    """A schema literal: strings bare, everything else (numbers, booleans, null, lists, objects) as JSON."""
    return code(value) if isinstance(value, str) else jsonish(value)


def table(headers: list[str], rows: list[list[object]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return out


def banner(source: str) -> str:
    return f"<!-- Generated by {GENERATOR} from {source}. Do not edit by hand: change the generator and rerun it. -->"


WRITTEN: set[Path] = set()  # every file write() produced in this run, so stale generated files can be removed


def write(path: Path, lines: list[str]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    WRITTEN.add(path.resolve())
    text = "\n".join(lines).rstrip("\n") + "\n"
    text = re.sub(r"\n{3,}", "\n\n", text)
    path.write_bytes(text.encode("utf-8"))
    return len(text.encode("utf-8"))


def file_slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
